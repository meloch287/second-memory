// Та же основа, что в findMember: срезаем хвостовые гласные/ь/й.
export const nickStem = (s) =>
  String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/[ауыоеиюяьй]+$/, '');

const MAP = new Map();
for (const group of GROUPS) {
  const canon = nickStem(group[0]);
  for (const variant of group) {
    const st = nickStem(variant);
    // первый выигрывает: «сер» из группы Сергея не должен перебиваться позже
    if (st.length >= 2 && !MAP.has(st)) MAP.set(st, canon);
  }
}

// Каноническая основа имени: «серёжу» -> «серге», «саню» -> «александр».
// Незнакомое имя возвращает собственную основу - сравнение всё равно работает.
export function canonStem(word) {
  const st = nickStem(word);
  if (MAP.get(st)) return MAP.get(st);
  // прозвище-прилагательное в косвенном падеже: «серому», «серого», «серым».
  // Отрезаем хвост в 1-2 буквы и пробуем снова - но только точное попадание
  // в словарь, иначе «санитар» уехал бы в «Александра».
  for (const cut of [1, 2]) {
    const shorter = st.slice(0, -cut);
    if (shorter.length >= 3 && MAP.has(shorter)) return MAP.get(shorter);
  }
  return st;
}

// Один ли это человек по имени (с учётом уменьшительных и падежей).
export function sameName(a, b) {
  const x = canonStem(a);
  const y = canonStem(b);
  return Boolean(x) && x === y;
}
