// Гард против «обещал контент, но не выдал»: детекция запроса-на-контент +
// ответа-отговорки. Чисто детерминированно, без обращения к ИИ.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { isContentDeferral } from '../src/ai.mjs';

const plan = 'Вот план:\n1. Жим лёжа 4x10\n2. Присед 4x8\n3. Тяга 3x12';

test('отговорка на запрос рецепта -> true', () => {
  assert.equal(isContentDeferral('дай рецепт блинчиков', 'Сейчас накидаю, подожди чуток'), true);
});

test('отговорка временем суток на план -> true', () => {
  assert.equal(
    isContentDeferral('составь план питания на день', 'Макс, ну какой план на ночь глядя? Давай завтра с утра составлю'),
    true,
  );
});

test('короткий встречный вопрос вместо контента -> true', () => {
  assert.equal(isContentDeferral('составь план тренировок', 'А на что упор - масса или похудение?'), true);
});

test('реальный план со списком -> false (контент выдан)', () => {
  assert.equal(isContentDeferral('выдай план тренировок на неделю', plan), false);
});

test('не запрос контента - гард не срабатывает', () => {
  assert.equal(isContentDeferral('привет, как сам?', 'Да норм, сейчас чай пью'), false);
});

test('«как приготовить блины» - запрос контента, отговорка ловится', () => {
  assert.equal(isContentDeferral('как приготовить блины?', 'Ща расскажу, момент'), true);
});

test('развёрнутый ответ без списка, но длинный -> false', () => {
  const long = 'Небо голубое потому, что солнечный свет рассеивается в атмосфере, '.repeat(6);
  assert.equal(isContentDeferral('расскажи почему небо голубое', long), false);
});
