// «поставь напоминание» / «напоминание …» тоже создаёт напоминание-задачу,
// не заметку (нашла мега-батарея по напоминалкам).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseMessage } from '../src/parser.mjs';

const NOW = new Date('2026-07-06T06:00:00.000Z'); // пн 6 июля, 09:00 МСК

for (const t of [
  'поставь напоминание через 10 минут позвонить маме',
  'поставь напоминание завтра в 15:00 оплатить счёт',
  'поставь напоминание через 3 дня забрать посылку',
  'напоминание 29 июля переспросить про зп',
  'сделай напоминание в 18:00 вынести мусор',
]) {
  test(`напоминание-глагол → задача: «${t}»`, () => {
    const r = parseMessage(t, NOW);
    assert.equal(r.kind, 'entry');
    assert.equal(r.entry.type, 'task', `должно быть task, а не ${r.entry?.type}`);
  });
}

// не ломаем: «напоминания нет», «в напоминалке» как обычный текст не обязаны быть задачей,
// но реальные глаголы «напомни» по-прежнему задача
test('«напомни …» по-прежнему задача', () => {
  assert.equal(parseMessage('напомни через час позвонить', NOW).entry.type, 'task');
});
