// Явное «запомни ...» - мгновенная запись, без ожидания фонового worker'а.
//
// Живой случай: человек прислал длинную идею со словом «запомни», бот ответил
// «идею понял», но факт появился только после того, как фоновый worker разгрёб
// очередь (а он в тот день лежал вместе с провайдером). На вопрос «ты записал?»
// ответить было нечего. Просьба запомнить - это не болтовня: сохраняем сразу,
// дословно и подтверждаем.

// «запомни», «запиши», «заметь», «сохрани» + содержательный остаток.
// Обращение к боту в начале («Толик, запомни ...») не мешает.
// NB: \b в JS не знает кириллицы («запомни\b» перед пробелом не сработает) -
// границу слова закрываем lookahead'ом.
const RE = /^(?:[а-яёa-z]{3,12}[,!]?\s+)?(?:запомни(?:те)?|запиши|заметь|сохрани)(?![а-яё])\s*[:,-]?\s*([\s\S]+)$/i;

// Слова, после которых идёт не факт, а команда другому сценарию.
// «запомни меня» / «запомни это» без продолжения - не заметка.
const EMPTY = /^(?:это|то|меня|его|её|ее|их|нас|всё|все|пожалуйста|плиз)[.!?]*$/i;

export function parseRemember(text) {
  const raw = String(text || '').trim();
  if (!raw) return null;
  const m = raw.match(RE);
  if (!m) return null;
  // «запомнил», «запишись», «заметил» - похожие слова, но не просьба
  if (/^(?:[а-яёa-z]{3,12}[,!]?\s+)?(?:запомнил|записал|заметил|сохранил)/i.test(raw)) return null;
  let body = m[1].trim().replace(/^(?:пожалуйста|плиз)[,\s]+/i, '').trim();
  // «запомни идеи\n\n1) ...» - слово-заголовок само по себе фактом не является,
  // но вместе с продолжением оно часть заметки, поэтому режем только его одного
  if (/^(?:иде[юяи]|идею|мысль|заметку|инфу|информацию)[:,]?$/i.test(body)) return null;
  if (!body || EMPTY.test(body) || body.length < 6) return null;
  return body.slice(0, 1500);
}

// Короткое эхо: первая строка заметки, чтобы человек видел, ЧТО записано.
export function rememberEcho(body) {
  const lines = String(body).split('\n').map((s) => s.trim()).filter(Boolean);
  // «идеи\n\n1) внедрить...»: первая строка бывает заголовком в одно слово -
  // эхом из неё человек не поймёт, что записалось, поэтому добираем следующую
  let out = lines[0] || '';
  for (let i = 1; i < lines.length && out.length < 24; i++) out += ' - ' + lines[i];
  return out.length > 110 ? out.slice(0, 110).trimEnd() + '…' : out;
}
