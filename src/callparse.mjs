// Разбор просьбы «позови такого-то [и передай ему то-то]».
//
// Живые баги из «Банды»:
//   «Маму позови сообщи ей об этом» -> бот искал участника «Сообщи ей об этом»
//   (имя стоит ПЕРЕД глаголом, а хвост - поручение);
//   «Позови ты» -> искал участника «Ты»;
//   «разбуди толик аню» -> между глаголом и именем стоит обращение к боту.
// Раньше это был один regexp прямо в group.mjs, который забирал ВЕСЬ хвост
// как имя. Теперь разбор отдельный и покрыт тестами.

// Глаголы вызова: повелительное («позови»), вежливое/мн.ч. («позовите»),
// инфинитив после модального («можешь позвать»). Народное «тегани» тоже.
const CALL = [
  'т[еэ]г(?:ни+|ните|ай|айте|ани|аните|нуть|ануть)',
  'пингани(?:те)?', 'пингуй(?:те)?', 'пингануть',
  'позови(?:те)?', 'позвать',
  'призови(?:те)?', 'призвать',
  'зови(?:те)?', 'звать',
  'дерни(?:те)?', 'дёрни(?:те)?', 'дернуть', 'дёрнуть',
  'свистни(?:те)?', 'свистнуть',
  'крикни(?:те)?', 'крикнуть',
  'кликни(?:те)?', 'кликнуть',
  'разбуди(?:те)?', 'разбудить',
  'подними(?:те)?',
].join('|');

// Глаголы поручения: то, что идёт ПОСЛЕ имени и адресовано боту.
const RELAY = '(?:скажи|скажите|передай|передайте|напиши|напишите|сообщи|сообщите|спроси|спросите|уточни|попроси|намекни|объясни)';

const RE_CALL_FIRST = new RegExp(`(?:^|[\\s,!])(?:${CALL})(?![а-яё])\\s+@?(.+)$`, 'i');
// «Маму позови», «Серёгу, дёрни» - имя впереди глагола
const RE_NAME_FIRST = new RegExp(`(?:^|[\\s,!])@?([А-Яа-яЁёA-Za-z][А-Яа-яЁёA-Za-z0-9_]{1,31})[,\\s]+(?:${CALL})(?![а-яё])(.*)$`, 'i');
const RE_RELAY_HEAD = new RegExp(`^(?:и\\s+)?${RELAY}(?![а-яё])`, 'i');
// «позови всех», «скинь клич пацанам», «все сюда»
const RE_ALL = new RegExp(
  `(?:^|[\\s,!])(?:(?:${CALL}|собери(?:те)?|созови(?:те)?)\\s+(?:всех|всем|все|народ|пацанов|ребят|тут\\s+всех)` +
    `|скинь\\s+клич|кинь\\s+клич)|^@?все\\s+сюда`,
  'i'
);

// Местоимения и обрывки: именем быть не могут.
export const NOT_A_NAME = /^(?:ты|вы|я|мы|он|она|они|нас|вас|их|кто|кого|кого[- ]нибудь|кого[- ]то|сюда|туда|тут|там|сам|сама|уже|быстро|давай|плиз|пожалуйста|его|её|ее)$/i;

// Слова, которые стоят рядом с именем, но именем не являются: обращение к боту,
// предлоги, вежливость. Из-за них «разбуди толик аню» и «кликни на серегу»
// раньше уезжали в поиск участника «толик» и «на».
const FILLER = /^(?:толик|толян|толя|бот|ботяра|эй|слушай|слышь|плиз|плз|пожалуйста|пожалуста|срочно|быстро|давай|на|к|ко|в|во|у|же|ка|там|тут|нибудь|кто)$/i;

const clean = (s) => String(s || '').replace(/^[\s,:-]+/, '').replace(/[,!?.\s]+$/, '').trim();

// Хвост-поручение: «и скажи что опоздаю» -> «опоздаю». Пустая отговорка
// вроде «сообщи ей об этом» смысла не несёт - её отбрасываем.
function relayBody(tail) {
  const t = clean(tail);
  if (!t || !RE_RELAY_HEAD.test(t)) return null;
  // NB: \b не знает кириллицы - границы через lookahead, и чистим на каждом шаге
  let body = clean(t.replace(RE_RELAY_HEAD, ''));
  body = clean(body.replace(/^(?:ему|ей|им|их)(?![а-яё])/i, ''));
  body = clean(body.replace(/^(?:что|чтобы|про|об|о)(?![а-яё])/i, ''));
  if (!body || /^(?:это|этом|том|то же|тоже|там|этого)$/i.test(body) || body.length < 3) return null;
  return body;
}

// Кандидаты в имя: слова хвоста по порядку, без мусора. Вызывающий код
// проверяет их по реестру и берёт первое совпадение - так «разбуди толик аню»
// доходит до «аню», а «позови сережу пожалуста» не спотыкается о хвост.
function candidatesOf(rest) {
  const words = clean(rest).split(/\s+/).filter(Boolean);
  const out = [];
  for (const w of words) {
    const word = w.replace(/^@/, '').replace(/[,!?.:;]+$/, '');
    if (!word || FILLER.test(word) || NOT_A_NAME.test(word)) continue;
    if (RE_RELAY_HEAD.test(word)) break; // дальше идёт поручение, не имя
    if (!/^[А-Яа-яЁёA-Za-z][А-Яа-яЁёA-Za-z0-9_]*$/.test(word)) continue;
    out.push(word);
    if (out.length >= 4) break;
  }
  return out;
}

// { who, candidates, relay } или null, если это вообще не просьба позвать.
// who === '*' - зовут всех. who === null + pronoun - в просьбе нет имени.
export function parseCallRequest(text) {
  const raw = String(text || '').trim();
  if (!raw) return null;
  if (RE_ALL.test(raw)) return { who: '*', candidates: [], relay: null };

  let rest = null;
  let tail = '';
  const m1 = raw.match(RE_CALL_FIRST);
  if (m1) {
    const after = clean(m1[1]);
    // «позови сообщи ей» - сразу поручение, значит имя стояло до глагола
    if (!RE_RELAY_HEAD.test(after)) {
      rest = after;
      tail = after.split(/\s+/).slice(1).join(' ');
    }
  }
  if (rest === null) {
    const m2 = raw.match(RE_NAME_FIRST);
    if (m2) {
      rest = clean(m2[1]);
      tail = clean(m2[2]);
    }
  }
  if (rest === null) return m1 ? { who: null, candidates: [], relay: null } : null;

  const candidates = candidatesOf(rest);
  const first = clean(rest).split(/\s+/)[0]?.replace(/^@/, '').replace(/[,!?.]+$/, '') || '';
  if (!candidates.length) {
    // «позови ты» / «позови его» - местоимение вместо имени
    const pronoun = NOT_A_NAME.test(first) ? first.toLowerCase() : null;
    return { who: null, candidates: [], relay: null, ...(pronoun ? { pronoun } : {}) };
  }
  return { who: candidates[0], candidates, relay: relayBody(tail) };
}
